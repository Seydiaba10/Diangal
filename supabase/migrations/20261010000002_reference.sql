-- DIANGAL · référentiels (lecture publique, écriture admin).

create table public.regions (
  id smallint primary key,
  name text not null unique
);

create table public.cities (
  id smallint generated by default as identity primary key,
  region_id smallint not null references public.regions,
  name text not null,
  slug text not null unique
);

create table public.neighborhoods (
  id integer generated by default as identity primary key,
  city_id smallint not null references public.cities on delete cascade,
  name text not null,
  unique (city_id, name)
);

create table public.levels (
  id smallint primary key,
  code text not null unique,
  name text not null,
  cycle public.cycle not null,
  sort_order smallint not null,
  exam_type public.exam_type
);

create table public.series (
  id smallint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  description text
);

-- Séries valides par niveau (2nde : L, S ; 1re et Terminale : L1, L2, L', S1…S5, G, T1, T2).
create table public.level_series (
  level_id smallint not null references public.levels on delete cascade,
  series_id smallint not null references public.series on delete cascade,
  primary key (level_id, series_id)
);

create table public.subjects (
  id smallint generated by default as identity primary key,
  code text not null unique,
  slug text not null unique,
  name text not null,
  color_token text not null,
  icon text not null
);

-- « Programme » : une matière dans un niveau (et une série au lycée), avec son coefficient.
create table public.programs (
  id integer generated by default as identity primary key,
  level_id smallint not null references public.levels,
  series_id smallint references public.series,
  subject_id smallint not null references public.subjects,
  coefficient numeric(3, 1) not null default 1 check (coefficient > 0),
  weekly_hours numeric(3, 1),
  sort_order smallint not null default 0,
  unique nulls not distinct (level_id, series_id, subject_id)
);
create index programs_subject_idx on public.programs (subject_id);

-- Dates des examens nationaux, saisies par l'admin : alimentent le compte à rebours.
create table public.exam_sessions (
  id text primary key,
  exam_type public.exam_type not null,
  year smallint not null,
  starts_on date not null,
  ends_on date,
  is_official boolean not null default false,
  unique (exam_type, year)
);
