-- DIANGAL · offres, abonnements (pass prépayés), paiements, réglages et journal d'audit.

create table public.plans (
  id smallint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  price_fcfa integer not null check (price_fcfa > 0),
  duration_days integer not null check (duration_days > 0),
  is_active boolean not null default true,
  sort_order smallint not null default 0
);

create table public.subscriptions (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.profiles on delete cascade,
  payer_id uuid not null references public.profiles,
  plan_id smallint not null references public.plans,
  status text not null default 'active' check (status in ('active', 'expired', 'cancelled')),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  payment_id uuid,
  created_at timestamptz not null default now(),
  check (starts_at < ends_at)
);
create index subscriptions_student_idx on public.subscriptions (student_id, ends_at desc);

-- Montants en FCFA entiers (le XOF n'a pas de centimes). Écriture réservée au serveur (webhook).
create table public.payments (
  id uuid primary key default gen_random_uuid(),
  reference text not null unique,
  payer_id uuid not null references public.profiles,
  beneficiary_id uuid references public.profiles,
  purpose public.payment_purpose not null,
  plan_id smallint references public.plans,
  booking_id uuid references public.bookings,
  amount_fcfa integer not null check (amount_fcfa > 0),
  provider text not null check (provider in ('paydunya', 'wave')),
  channel public.payment_channel,
  status public.payment_status not null default 'pending',
  provider_ref text unique,
  created_at timestamptz not null default now(),
  paid_at timestamptz
);
create index payments_payer_idx on public.payments (payer_id, created_at desc);

alter table public.subscriptions
  add constraint subscriptions_payment_fk foreign key (payment_id) references public.payments;

-- Webhooks reçus : la contrainte UNIQUE rend leur traitement idempotent.
create table public.payment_events (
  id bigint generated always as identity primary key,
  provider text not null,
  event_id text not null,
  payload jsonb not null,
  received_at timestamptz not null default now(),
  processed_at timestamptz,
  unique (provider, event_id)
);

create table public.platform_settings (
  key text primary key,
  value jsonb not null
);

create table public.audit_logs (
  id bigint generated always as identity primary key,
  actor_id uuid references public.profiles,
  action text not null,
  entity_type text not null,
  entity_id text,
  meta jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index audit_logs_created_idx on public.audit_logs (created_at desc);
